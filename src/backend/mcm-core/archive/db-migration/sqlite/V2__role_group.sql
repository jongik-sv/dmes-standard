-- 동기화 정책: 그룹은 직접부여 ROLE 과 별개로 union (그룹 해제 시 직접 부여 ROLE 은 유지).

CREATE TABLE IF NOT EXISTS TB_SEC_ROLE_GROUP (
    GROUP_ID     TEXT PRIMARY KEY,
    GROUP_NM     TEXT,
    GROUP_DESC   TEXT,
    USE_YN       TEXT DEFAULT 'Y',
    C_USR_ID     TEXT, C_AT TEXT, C_SVC_ID TEXT, C_PGM_ID TEXT,
    U_USR_ID     TEXT, U_AT TEXT, U_SVC_ID TEXT, U_PGM_ID TEXT,
    VER          INTEGER
);

CREATE TABLE IF NOT EXISTS TB_SEC_ROLE_GROUP_ROLE (
    GROUP_ID     TEXT NOT NULL,
    ROLE_ID      TEXT NOT NULL,
    C_USR_ID     TEXT, C_AT TEXT, C_SVC_ID TEXT, C_PGM_ID TEXT,
    U_USR_ID     TEXT, U_AT TEXT, U_SVC_ID TEXT, U_PGM_ID TEXT,
    VER          INTEGER,
    PRIMARY KEY (GROUP_ID, ROLE_ID)
);

CREATE TABLE IF NOT EXISTS TB_SEC_ROLE_GROUP_USER (
    GROUP_ID     TEXT NOT NULL,
    USER_ID      TEXT NOT NULL,
    C_USR_ID     TEXT, C_AT TEXT, C_SVC_ID TEXT, C_PGM_ID TEXT,
    U_USR_ID     TEXT, U_AT TEXT, U_SVC_ID TEXT, U_PGM_ID TEXT,
    VER          INTEGER,
    PRIMARY KEY (GROUP_ID, USER_ID)
);

CREATE INDEX IF NOT EXISTS IDX_SEC_RGR_GROUP    ON TB_SEC_ROLE_GROUP_ROLE(GROUP_ID);
CREATE INDEX IF NOT EXISTS IDX_SEC_RGR_ROLE     ON TB_SEC_ROLE_GROUP_ROLE(ROLE_ID);
CREATE INDEX IF NOT EXISTS IDX_SEC_RGU_GROUP    ON TB_SEC_ROLE_GROUP_USER(GROUP_ID);
CREATE INDEX IF NOT EXISTS IDX_SEC_RGU_USER     ON TB_SEC_ROLE_GROUP_USER(USER_ID);
