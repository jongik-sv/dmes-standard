package com.dongkuk.dmes.mdm.dmb.layout;

/**
 * 레이아웃 저장 거부 코드(TSK-05-02 design.md §6.2). 05-03 몫(유효 식·차원·자리 용량·unit_item 대상)은 TSK-05-03 이 L12~L15 로
 * 더했다(TSK-05-03 design.md D7 — 03 거부 7종 중 #1=L01·#5=L02(FILLER_LENGTH)·#6=L05 는 05-02 코드를 그대로 쓴다).
 */
public enum LayoutIssueCode {
    /** DATA·CONST·AUTO 항목의 컬럼이 컬럼 사전에 없다. */
    L01,
    /** fill_kind 의 닫힌 칸에 값이 있다. */
    L02,
    /** 필수 칸이 비었다(fill_kind, 컬럼, AUTO 종류, FILLER 길이 ≥ 1). */
    L03,
    /** AUTO 종류가 SEND_TIME·MSG_LENGTH·SEQ·LAYOUT_ID 가 아니다. */
    L04,
    /** 전송 단위와 단위 항목을 함께 넣었다. */
    L05,
    /** 같은 레이아웃에 같은 컬럼을 두 번 넣었다. */
    L06,
    /** 항목 길이를 파생할 수 없다(유효 도메인 길이 없음). */
    L07,
    /** 숫자 표현 형식 위반(숫자가 아닌 도메인·형식 문자열·암묵 소수 자리). */
    L08,
    /** 헤더 구성 위반(HEADER 가 아닌 레이아웃·같은 헤더 중복·없는 헤더). */
    L09,
    /** 상수 재정의 대상이 이 전문에 쌓인 헤더의 CONST 항목이 아니다. */
    L10,
    /** 기본 속성 위반(이름·시스템·EAI·대상 레이아웃). */
    L11,
    /** 03 거부 #2 — CONST 값(본문·헤더 기본값·전문 재정의)이 도메인 유효 식(타입·표준식·바이트 길이)을 어긴다(TSK-05-03). */
    L12,
    /** 03 거부 #3 — 전송 단위가 단위 마스터에 없거나 도메인 기준 단위가 없거나 차원이 다르다(TSK-05-03). */
    L13,
    /** 03 거부 #4 — 숫자 표현 자리가 도메인의 자리·부호·소수점·전송 단위 증가를 담지 못한다(TSK-05-03). */
    L14,
    /** 03 거부 #7 — 단위 항목이 같은 레이아웃의 다른 항목을 가리키지 않는다(TSK-05-03). */
    L15,
    /** 합성 총 길이가 MSG_LENGTH(AUTO) 칸 자리수를 넘는다(D-144 3단계 — 헤더 길이 변경 영향). */
    L16
}
