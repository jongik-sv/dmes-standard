CREATE TABLE TB_MDM_UNIT (
    UNIT_CODE VARCHAR(20) NOT NULL,
    DIMENSION VARCHAR(50) NOT NULL,
    BASE_UNIT VARCHAR(20) NOT NULL,
    FACTOR NUMERIC(18,9) NOT NULL,
    CHG_SEQ INTEGER NOT NULL DEFAULT 0,
    C_USR_ID VARCHAR(100),
    C_AT TIMESTAMP,
    C_SVC_ID VARCHAR(100),
    C_PGM_ID VARCHAR(100),
    U_USR_ID VARCHAR(100),
    U_AT TIMESTAMP,
    U_SVC_ID VARCHAR(100),
    U_PGM_ID VARCHAR(100),
    VER BIGINT,
    CONSTRAINT PK_TB_MDM_UNIT PRIMARY KEY (UNIT_CODE)
);

CREATE TABLE TB_MDM_TERM (
    TERM_ID INTEGER CONSTRAINT PK_TB_MDM_TERM PRIMARY KEY AUTOINCREMENT,
    TERM_NAME TEXT NOT NULL,
    SENSE_NO INTEGER NOT NULL,
    DEFINITION TEXT NOT NULL,
    CONTEXT TEXT,
    ENG_NAME TEXT,
    ENG_ABBR VARCHAR(50),
    SYNONYMS TEXT CONSTRAINT CK_TB_MDM_TERM_SYNONYMS_JSON CHECK (SYNONYMS IS NULL OR json_valid(SYNONYMS)),
    ALIASES TEXT CONSTRAINT CK_TB_MDM_TERM_ALIASES_JSON CHECK (ALIASES IS NULL OR json_valid(ALIASES)),
    SYSTEMS TEXT CONSTRAINT CK_TB_MDM_TERM_SYSTEMS_JSON CHECK (SYSTEMS IS NULL OR json_valid(SYSTEMS)),
    STD_BASIS TEXT,
    OWNER_DEPT TEXT,
    OWNER_ID VARCHAR(50),
    SRC_ORIGIN TEXT,
    EMBEDDING BLOB,
    EMBEDDING_MODEL VARCHAR(100),
    C_USR_ID VARCHAR(100),
    C_AT TIMESTAMP,
    C_SVC_ID VARCHAR(100),
    C_PGM_ID VARCHAR(100),
    U_USR_ID VARCHAR(100),
    U_AT TIMESTAMP,
    U_SVC_ID VARCHAR(100),
    U_PGM_ID VARCHAR(100),
    VER BIGINT
);
CREATE UNIQUE INDEX UX_TB_MDM_TERM_NAME_SENSE ON TB_MDM_TERM (TERM_NAME, SENSE_NO);
CREATE UNIQUE INDEX UX_TB_MDM_TERM_ABBR ON TB_MDM_TERM (ENG_ABBR) WHERE ENG_ABBR IS NOT NULL;

CREATE TABLE TB_MDM_DOMAIN (
    DOMAIN_ID INTEGER CONSTRAINT PK_TB_MDM_DOMAIN PRIMARY KEY AUTOINCREMENT,
    DOMAIN_NAME TEXT NOT NULL,
    STD_NAME VARCHAR(50) NOT NULL,
    PARENT_DOMAIN_ID INTEGER,
    DOMAIN_KIND VARCHAR(20) NOT NULL,
    DATA_TYPE VARCHAR(20) NOT NULL,
    LENGTH INTEGER,
    SCALE INTEGER,
    UNIT_CODE VARCHAR(20),
    MARU_CODE_ID VARCHAR(50),
    CATE_ID VARCHAR(50),
    STD_RULE TEXT,
    STD_AST TEXT CONSTRAINT CK_TB_MDM_DOMAIN_STD_AST_JSON CHECK (STD_AST IS NULL OR json_valid(STD_AST)),
    BIZ_RULE TEXT,
    BIZ_AST TEXT CONSTRAINT CK_TB_MDM_DOMAIN_BIZ_AST_JSON CHECK (BIZ_AST IS NULL OR json_valid(BIZ_AST)),
    DESCRIPTION TEXT,
    EXAMPLES TEXT CONSTRAINT CK_TB_MDM_DOMAIN_EXAMPLES_JSON CHECK (EXAMPLES IS NULL OR json_valid(EXAMPLES)),
    TEST_CASES TEXT CONSTRAINT CK_TB_MDM_DOMAIN_TEST_CASES_JSON CHECK (TEST_CASES IS NULL OR json_valid(TEST_CASES)),
    CHG_SEQ INTEGER NOT NULL DEFAULT 0,
    C_USR_ID VARCHAR(100),
    C_AT TIMESTAMP,
    C_SVC_ID VARCHAR(100),
    C_PGM_ID VARCHAR(100),
    U_USR_ID VARCHAR(100),
    U_AT TIMESTAMP,
    U_SVC_ID VARCHAR(100),
    U_PGM_ID VARCHAR(100),
    VER BIGINT,
    CONSTRAINT FK_TB_MDM_DOMAIN_DOMAIN FOREIGN KEY (PARENT_DOMAIN_ID) REFERENCES TB_MDM_DOMAIN (DOMAIN_ID),
    CONSTRAINT FK_TB_MDM_DOMAIN_UNIT FOREIGN KEY (UNIT_CODE) REFERENCES TB_MDM_UNIT (UNIT_CODE),
    -- FK_TB_MDM_DOMAIN_CODE(MARU_CODE_ID→TB_MDM_CODE) 는 이번 V3 에 걸지 않는다(D1) — TB_MDM_CODE 가
    -- 아직 없어(F2) 걸면 이 테이블·자식 TB_MDM_COLUMN 에 대한 모든 쓰기가 막힌다(F1). TSK-06-01 이 후행 추가.
    CONSTRAINT CK_TB_MDM_DOMAIN_CODE CHECK (DOMAIN_KIND <> 'CODE' OR STD_RULE IS NULL),
    CONSTRAINT CK_TB_MDM_DOMAIN_FLAG CHECK (DOMAIN_KIND <> 'FLAG' OR PARENT_DOMAIN_ID IS NOT NULL OR STD_RULE IS NOT NULL)
);
CREATE INDEX IX_TB_MDM_DOMAIN_PARENT ON TB_MDM_DOMAIN (PARENT_DOMAIN_ID);

CREATE TABLE TB_MDM_COLUMN (
    COLUMN_ID INTEGER CONSTRAINT PK_TB_MDM_COLUMN PRIMARY KEY AUTOINCREMENT,
    COLUMN_NAME TEXT NOT NULL,
    LABEL_LONG TEXT,
    LABEL_MID TEXT,
    LABEL_SHORT TEXT,
    PHYS_NAME VARCHAR(50) NOT NULL,
    DESCRIPTION TEXT,
    DOMAIN_ID INTEGER NOT NULL,
    REQUIRED INTEGER NOT NULL DEFAULT 0,
    DEFAULT_VALUE VARCHAR(50),
    REF_KIND VARCHAR(20),
    REF_TARGET VARCHAR(50),
    REF_CATE_ID VARCHAR(50),
    TERM_IDS TEXT CONSTRAINT CK_TB_MDM_COLUMN_TERM_IDS_JSON CHECK (TERM_IDS IS NULL OR json_valid(TERM_IDS)),
    USAGE_NOTE TEXT,
    CHG_SEQ INTEGER NOT NULL DEFAULT 0,
    C_USR_ID VARCHAR(100),
    C_AT TIMESTAMP,
    C_SVC_ID VARCHAR(100),
    C_PGM_ID VARCHAR(100),
    U_USR_ID VARCHAR(100),
    U_AT TIMESTAMP,
    U_SVC_ID VARCHAR(100),
    U_PGM_ID VARCHAR(100),
    VER BIGINT,
    CONSTRAINT FK_TB_MDM_COLUMN_DOMAIN FOREIGN KEY (DOMAIN_ID) REFERENCES TB_MDM_DOMAIN (DOMAIN_ID),
    CONSTRAINT CK_TB_MDM_COLUMN_REQUIRED CHECK (REQUIRED IN (0,1))
);
CREATE UNIQUE INDEX UX_TB_MDM_COLUMN_NAME ON TB_MDM_COLUMN (COLUMN_NAME);
CREATE UNIQUE INDEX UX_TB_MDM_COLUMN_PHYS_NAME ON TB_MDM_COLUMN (PHYS_NAME);

CREATE TABLE TB_MDM_COLUMN_SYSTEM (
    COLUMN_ID INTEGER NOT NULL,
    SYSTEM_CODE VARCHAR(20) NOT NULL,
    PHYS_NAME VARCHAR(50) NOT NULL,
    TRANSFORM VARCHAR(50),
    NOTE TEXT,
    C_USR_ID VARCHAR(100),
    C_AT TIMESTAMP,
    C_SVC_ID VARCHAR(100),
    C_PGM_ID VARCHAR(100),
    U_USR_ID VARCHAR(100),
    U_AT TIMESTAMP,
    U_SVC_ID VARCHAR(100),
    U_PGM_ID VARCHAR(100),
    VER BIGINT,
    CONSTRAINT PK_TB_MDM_COLUMN_SYSTEM PRIMARY KEY (COLUMN_ID, SYSTEM_CODE, PHYS_NAME),
    CONSTRAINT FK_TB_MDM_COLUMN_SYSTEM_COLUMN FOREIGN KEY (COLUMN_ID) REFERENCES TB_MDM_COLUMN (COLUMN_ID),
    CONSTRAINT FK_TB_MDM_COLUMN_SYSTEM_SYSTEM FOREIGN KEY (SYSTEM_CODE) REFERENCES TB_MDM_SYSTEM (SYSTEM_CODE)
);
CREATE INDEX IX_TB_MDM_COLUMN_SYSTEM_SYS_PHYS ON TB_MDM_COLUMN_SYSTEM (SYSTEM_CODE, PHYS_NAME);

