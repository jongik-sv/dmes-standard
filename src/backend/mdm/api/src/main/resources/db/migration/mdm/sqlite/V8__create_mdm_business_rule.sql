-- 보류 테이블(수신 로그, D1·D-019). 엔티티·리포지토리를 붙이지 않는다. BODY 는 요청 원문이라 JSON CHECK 를 두지 않는다(F5).
CREATE TABLE TB_MDM_RULE_RECV (
    RECV_ID INTEGER CONSTRAINT PK_TB_MDM_RULE_RECV PRIMARY KEY AUTOINCREMENT,
    MARU_RULE_ID VARCHAR(50),
    SOURCE_SYSTEM VARCHAR(20) NOT NULL,
    SOURCE_REF VARCHAR(50),
    REQ_KIND VARCHAR(20) NOT NULL,
    RECEIVED_AT TEXT NOT NULL,
    BODY TEXT NOT NULL,
    "RESULT" VARCHAR(20),
    RESULT_DETAIL TEXT,
    VER INTEGER,
    PROCESSED_AT TEXT,
    C_USR_ID VARCHAR(100),
    C_AT TIMESTAMP,
    C_SVC_ID VARCHAR(100),
    C_PGM_ID VARCHAR(100),
    U_USR_ID VARCHAR(100),
    U_AT TIMESTAMP,
    U_SVC_ID VARCHAR(100),
    U_PGM_ID VARCHAR(100),
    AUD_VER BIGINT,
    CONSTRAINT FK_TB_MDM_RULE_RECV_RULE FOREIGN KEY (MARU_RULE_ID) REFERENCES TB_MDM_RULE (MARU_RULE_ID),
    CONSTRAINT FK_TB_MDM_RULE_RECV_SYSTEM FOREIGN KEY (SOURCE_SYSTEM) REFERENCES TB_MDM_SYSTEM (SYSTEM_CODE),
    CONSTRAINT CK_TB_MDM_RULE_RECV_REQ CHECK (REQ_KIND IN ('VERSION','CANCEL','DEPRECATE')),
    CONSTRAINT CK_TB_MDM_RULE_RECV_RESULT CHECK ("RESULT" IS NULL OR "RESULT" IN ('OK','REJECTED','FAILED'))
);
