    RELEASED_AT DATETIME2(0) NULL,
    CANCELLED_AT DATETIME2(0) NULL,
    CANCEL_REASON NVARCHAR(MAX) NULL,
    ROW_VERSION BIGINT NOT NULL CONSTRAINT DF_TB_MDM_RULE_VER_ROW_VERSION DEFAULT (0),
    C_USR_ID VARCHAR(100) NULL,
    C_AT DATETIME2 NULL,
    C_SVC_ID VARCHAR(100) NULL,
    C_PGM_ID VARCHAR(100) NULL,
    U_USR_ID VARCHAR(100) NULL,
    U_AT DATETIME2 NULL,
    U_SVC_ID VARCHAR(100) NULL,
    U_PGM_ID VARCHAR(100) NULL,
    AUD_VER BIGINT NULL,
    CONSTRAINT PK_TB_MDM_RULE_VER PRIMARY KEY (MARU_RULE_ID, VER),
    CONSTRAINT FK_TB_MDM_RULE_VER_RULE FOREIGN KEY (MARU_RULE_ID) REFERENCES TB_MDM_RULE (MARU_RULE_ID),
