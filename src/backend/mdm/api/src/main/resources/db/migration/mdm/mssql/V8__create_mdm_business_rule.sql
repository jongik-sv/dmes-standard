    CONSTRAINT CK_TB_MDM_RULE_VER_HIT CHECK (HIT_POLICY IS NULL OR HIT_POLICY IN ('FIRST','UNIQUE','PRIORITY','COLLECT','ANY')),
    CONSTRAINT CK_TB_MDM_RULE_VER_APPLY CHECK (STATUS = 'DRAFT' OR (APPLY_FROM IS NOT NULL AND APPLY_TO IS NOT NULL)),
    CONSTRAINT CK_TB_MDM_RULE_VER_EMERGENCY_YN CHECK (EMERGENCY_YN IN ('Y','N'))
);

CREATE TABLE TB_MDM_RULE_VAR (
    MARU_RULE_ID VARCHAR(50) COLLATE Latin1_General_100_BIN2 NOT NULL,
    VER INT NOT NULL,
    VAR_ID INT NOT NULL,
    VAR_KIND VARCHAR(20) COLLATE Latin1_General_100_BIN2 NOT NULL,
    DISP_TYPE VARCHAR(20) COLLATE Latin1_General_100_BIN2 NULL,
    AXIS VARCHAR(20) COLLATE Latin1_General_100_BIN2 NULL,
    VAR_NAME VARCHAR(1000) COLLATE Latin1_General_100_BIN2 NULL,
    VAR_AST NVARCHAR(MAX) NULL,
    DOMAIN_ID BIGINT NULL,
    DATA_TYPE VARCHAR(20) COLLATE Latin1_General_100_BIN2 NULL,
    COLLECT_AGG VARCHAR(20) COLLATE Latin1_General_100_BIN2 NULL CONSTRAINT DF_TB_MDM_RULE_VAR_COLLECT_AGG DEFAULT ('LIST'),
    PRIO_LIST NVARCHAR(MAX) NULL,
    RES_GRP VARCHAR(50) COLLATE Latin1_General_100_BIN2 NULL,
    GRP_COND VARCHAR(MAX) NULL,
    GRP_COND_AST NVARCHAR(MAX) NULL,
    SEQ INT NOT NULL,
    LABEL NVARCHAR(100) NULL,
    DESCRIPTION NVARCHAR(MAX) NULL,
    C_USR_ID VARCHAR(100) NULL,
    C_AT DATETIME2 NULL,
    C_SVC_ID VARCHAR(100) NULL,
    C_PGM_ID VARCHAR(100) NULL,
    U_USR_ID VARCHAR(100) NULL,
    U_AT DATETIME2 NULL,
    U_SVC_ID VARCHAR(100) NULL,
    U_PGM_ID VARCHAR(100) NULL,
    AUD_VER BIGINT NULL,
    CONSTRAINT PK_TB_MDM_RULE_VAR PRIMARY KEY (MARU_RULE_ID, VER, VAR_ID),
    CONSTRAINT FK_TB_MDM_RULE_VAR_VER FOREIGN KEY (MARU_RULE_ID, VER) REFERENCES TB_MDM_RULE_VER (MARU_RULE_ID, VER) ON DELETE CASCADE,
    CONSTRAINT FK_TB_MDM_RULE_VAR_DOMAIN FOREIGN KEY (DOMAIN_ID) REFERENCES TB_MDM_DOMAIN (DOMAIN_ID),
    CONSTRAINT CK_TB_MDM_RULE_VAR_KIND CHECK (VAR_KIND IN ('COND','RESULT')),
    CONSTRAINT CK_TB_MDM_RULE_VAR_DISP CHECK (DISP_TYPE IS NULL OR DISP_TYPE IN ('Equal','1','2','Expression','Value')),
    CONSTRAINT CK_TB_MDM_RULE_VAR_AXIS CHECK (AXIS IS NULL OR AXIS IN ('ROW','COL','NONE')),
    CONSTRAINT CK_TB_MDM_RULE_VAR_DTYPE CHECK (DATA_TYPE IS NULL OR DATA_TYPE IN ('BOOLEAN','NUMBER','STRING','DATE')),
    CONSTRAINT CK_TB_MDM_RULE_VAR_AGG CHECK (COLLECT_AGG IS NULL OR COLLECT_AGG IN ('LIST','SUM','MIN','MAX','COUNT')),
    CONSTRAINT CK_TB_MDM_RULE_VAR_RESULT_NAME CHECK (VAR_KIND <> 'RESULT' OR VAR_NAME IS NOT NULL),
    CONSTRAINT CK_TB_MDM_RULE_VAR_VAR_AST_JSON CHECK (VAR_AST IS NULL OR ISJSON(VAR_AST) = 1),
    CONSTRAINT CK_TB_MDM_RULE_VAR_PRIO_LIST_JSON CHECK (PRIO_LIST IS NULL OR ISJSON(PRIO_LIST) = 1),
    CONSTRAINT CK_TB_MDM_RULE_VAR_GRP_COND_AST_JSON CHECK (GRP_COND_AST IS NULL OR ISJSON(GRP_COND_AST) = 1)
);
CREATE UNIQUE INDEX UX_TB_MDM_RULE_VAR_SEQ ON TB_MDM_RULE_VAR (MARU_RULE_ID, VER, VAR_KIND, SEQ);
CREATE UNIQUE INDEX UX_TB_MDM_RULE_VAR_NAME ON TB_MDM_RULE_VAR (MARU_RULE_ID, VER, VAR_NAME) WHERE VAR_KIND = 'RESULT';

