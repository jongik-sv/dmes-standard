-- TSK-08-01 design.md §1·§2·§6.0 — 06 영역(업무기준) 8테이블(MSSQL). 팀장 배정 버전 V8(V5~V7 은 비워 둔다).
-- 1차 텍스트는 docs/mdm/erd/06-business-rule.mssql.sql(TSK-02-03) 이되, 이 Task 가 확인한 지점에서 갈라진다(§6.1):
--   ① 모든 ROW_VERSION 은 BIGINT 로 쓴다 — D2, TSK-01-03 인계 ②.
--   ② VAR_NAME 은 인덱스 키가 될 수 있게 VARCHAR(1000) BIN2 로 쓴다(MAX 는 인덱스 키 불가) — D3, F13.
--   ③ 결과 열 VAR_NAME 필수 CHECK(CK_TB_MDM_RULE_VAR_RESULT_NAME)를 더한다 — D3, F14.
--   ④ DISP_TYPE 은 06 표기(Equal·1·2·Expression·Value)만 받는다(CK_TB_MDM_RULE_VAR_DISP) — D4, 06:1009.
-- 사용자 결정: 도커 금지로 MSSQL 실측 생략, DDL 리뷰로 대체(MdmBusinessRuleDdlParityTest + design.md §3.3 체크리스트).
-- 코드·키 칼럼은 BIN2 로 두 방언의 비교 결과를 같게 한다(규칙표 #19). 필터 인덱스는 QUOTED_IDENTIFIER ON 이 필요하다.

CREATE TABLE TB_MDM_RULE (
    MARU_RULE_ID VARCHAR(50) COLLATE Latin1_General_100_BIN2 NOT NULL,
    MARU_RULE_NAME NVARCHAR(100) NOT NULL,
    RULE_KIND VARCHAR(20) COLLATE Latin1_General_100_BIN2 NOT NULL,
    STATUS VARCHAR(20) COLLATE Latin1_General_100_BIN2 NOT NULL CONSTRAINT DF_TB_MDM_RULE_STATUS DEFAULT ('CREATED'),
    SOURCE_KIND VARCHAR(20) COLLATE Latin1_General_100_BIN2 NOT NULL,
    SOURCE_SYSTEM VARCHAR(20) COLLATE Latin1_General_100_BIN2 NULL,
    DESCRIPTION NVARCHAR(MAX) NULL,
    USAGE_NOTE NVARCHAR(MAX) NULL,
    LAST_VAR_ID INT NOT NULL CONSTRAINT DF_TB_MDM_RULE_LAST_VAR_ID DEFAULT (0),
    LAST_ROW_ID INT NOT NULL CONSTRAINT DF_TB_MDM_RULE_LAST_ROW_ID DEFAULT (0),
    LAST_CASE_ID INT NOT NULL CONSTRAINT DF_TB_MDM_RULE_LAST_CASE_ID DEFAULT (0),
    C_USR_ID VARCHAR(100) NULL,
    C_AT DATETIME2 NULL,
    C_SVC_ID VARCHAR(100) NULL,
    C_PGM_ID VARCHAR(100) NULL,
    U_USR_ID VARCHAR(100) NULL,
    U_AT DATETIME2 NULL,
    U_SVC_ID VARCHAR(100) NULL,
    U_PGM_ID VARCHAR(100) NULL,
    VER BIGINT NULL,
    CONSTRAINT PK_TB_MDM_RULE PRIMARY KEY (MARU_RULE_ID),
    CONSTRAINT FK_TB_MDM_RULE_SYSTEM_SRC FOREIGN KEY (SOURCE_SYSTEM) REFERENCES TB_MDM_SYSTEM (SYSTEM_CODE),
    CONSTRAINT CK_TB_MDM_RULE_KIND CHECK (RULE_KIND IN ('DECISION','DERIVE')),
    CONSTRAINT CK_TB_MDM_RULE_STATUS CHECK (STATUS IN ('CREATED','INUSE','DEPRECATED')),
    CONSTRAINT CK_TB_MDM_RULE_SRC_KIND CHECK (SOURCE_KIND IN ('MDM','EXTERNAL')),
    CONSTRAINT CK_TB_MDM_RULE_SRC_SYS CHECK ((SOURCE_KIND = 'EXTERNAL' AND SOURCE_SYSTEM IS NOT NULL) OR (SOURCE_KIND = 'MDM' AND SOURCE_SYSTEM IS NULL))
);

-- 보류 테이블(배포 대상, D1·D-019). 엔티티·리포지토리를 붙이지 않는다.
