--
-- 배경:
--   ERD 2차(erd-2nd-1012 §7.1). 관계선이 지나는 꺾임점을 다이어그램마다 둔다. 다이어그램 노드와 같이 버전 밖 표다.
--   관계는 MODEL_JSON 안에 있으므로 관계 FK 는 없다. 그 버전에 없는 관계의 행은 지우지 않고 화면이 그리지 않는다.
--   감사 9칼럼은 TB_MDM_ERD_DIAGRAM_NODE 와 같다(카운터 VER).
-- ============================================================

-- 다이어그램 위 관계선의 꺾임점(REL_UUID 는 MODEL_JSON 의 관계 키). POINTS_JSON = [{"x":정수,"y":정수},…] 1~50개.
CREATE TABLE TB_MDM_ERD_DIAGRAM_ROUTE (
    DIAGRAM_ID     VARCHAR2(50 CHAR)  NOT NULL,
    REL_UUID       VARCHAR2(50 CHAR)  NOT NULL,
    POINTS_JSON    CLOB               NOT NULL,
    C_USR_ID VARCHAR2(100 CHAR), C_AT TIMESTAMP(6), C_SVC_ID VARCHAR2(100 CHAR), C_PGM_ID VARCHAR2(100 CHAR),
    U_USR_ID VARCHAR2(100 CHAR), U_AT TIMESTAMP(6), U_SVC_ID VARCHAR2(100 CHAR), U_PGM_ID VARCHAR2(100 CHAR),
    VER            NUMBER(19),
    CONSTRAINT PK_TB_MDM_ERD_DIAGRAM_ROUTE PRIMARY KEY (DIAGRAM_ID, REL_UUID),
    CONSTRAINT FK_TB_MDM_ERD_DIAGRAM_ROUTE_DIAGRAM FOREIGN KEY (DIAGRAM_ID) REFERENCES TB_MDM_ERD_DIAGRAM (DIAGRAM_ID),
    CONSTRAINT CK_TB_MDM_ERD_DIAGRAM_ROUTE_POINTS CHECK (POINTS_JSON IS JSON STRICT)
);

COMMENT ON TABLE TB_MDM_ERD_DIAGRAM_ROUTE IS 'ERD 다이어그램 관계선 꺾임점';
COMMENT ON COLUMN TB_MDM_ERD_DIAGRAM_ROUTE.DIAGRAM_ID IS '다이어그램 아이디';
COMMENT ON COLUMN TB_MDM_ERD_DIAGRAM_ROUTE.REL_UUID IS '관계 아이디';
COMMENT ON COLUMN TB_MDM_ERD_DIAGRAM_ROUTE.POINTS_JSON IS '꺾임점 JSON';
COMMENT ON COLUMN TB_MDM_ERD_DIAGRAM_ROUTE.C_USR_ID IS '생성자 아이디';
COMMENT ON COLUMN TB_MDM_ERD_DIAGRAM_ROUTE.C_AT IS '생성일시';
COMMENT ON COLUMN TB_MDM_ERD_DIAGRAM_ROUTE.C_SVC_ID IS '생성 서비스 아이디';
COMMENT ON COLUMN TB_MDM_ERD_DIAGRAM_ROUTE.C_PGM_ID IS '생성 프로그램 아이디';
COMMENT ON COLUMN TB_MDM_ERD_DIAGRAM_ROUTE.U_USR_ID IS '수정자 아이디';
COMMENT ON COLUMN TB_MDM_ERD_DIAGRAM_ROUTE.U_AT IS '수정일시';
COMMENT ON COLUMN TB_MDM_ERD_DIAGRAM_ROUTE.U_SVC_ID IS '수정 서비스 아이디';
COMMENT ON COLUMN TB_MDM_ERD_DIAGRAM_ROUTE.U_PGM_ID IS '수정 프로그램 아이디';
COMMENT ON COLUMN TB_MDM_ERD_DIAGRAM_ROUTE.VER IS '버전';
