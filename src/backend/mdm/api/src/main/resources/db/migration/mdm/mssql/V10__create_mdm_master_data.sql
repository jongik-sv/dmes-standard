CREATE TABLE TB_MDM_DATA_RECV (
    RECV_ID BIGINT IDENTITY(1,1) NOT NULL,
    MARU_DATA_ID VARCHAR(50) COLLATE Latin1_General_100_BIN2 NULL,
    SOURCE_SYSTEM VARCHAR(20) COLLATE Latin1_General_100_BIN2 NOT NULL,
    SOURCE_REF VARCHAR(50) COLLATE Latin1_General_100_BIN2 NULL,
    RECEIVED_AT DATETIME2(0) NOT NULL,
    BODY NVARCHAR(MAX) NOT NULL,
    ROW_COUNT INT NOT NULL CONSTRAINT DF_TB_MDM_DATA_RECV_ROW_COUNT DEFAULT (0),
    [RESULT] VARCHAR(20) COLLATE Latin1_General_100_BIN2 NULL,
    RESULT_DETAIL NVARCHAR(MAX) NULL,
    CHG_SEQ BIGINT NULL,
    PROCESSED_AT DATETIME2(0) NULL,
    C_USR_ID VARCHAR(100) NULL,
    C_AT DATETIME2 NULL,
    C_SVC_ID VARCHAR(100) NULL,
    C_PGM_ID VARCHAR(100) NULL,
    U_USR_ID VARCHAR(100) NULL,
    U_AT DATETIME2 NULL,
    U_SVC_ID VARCHAR(100) NULL,
    U_PGM_ID VARCHAR(100) NULL,
    VER BIGINT NULL,
    CONSTRAINT PK_TB_MDM_DATA_RECV PRIMARY KEY (RECV_ID),
    CONSTRAINT FK_TB_MDM_DATA_RECV_DATA FOREIGN KEY (MARU_DATA_ID) REFERENCES TB_MDM_DATA (MARU_DATA_ID),
    CONSTRAINT FK_TB_MDM_DATA_RECV_SYSTEM FOREIGN KEY (SOURCE_SYSTEM) REFERENCES TB_MDM_SYSTEM (SYSTEM_CODE),
    CONSTRAINT CK_TB_MDM_DATA_RECV_RESULT CHECK ([RESULT] IS NULL OR [RESULT] IN ('OK','REJECTED','FAILED'))
);

CREATE TABLE TB_MDM_DATA_RECV_ITEM (
    RECV_ID BIGINT NOT NULL,
    SEQ INT NOT NULL,
    CODE VARCHAR(50) COLLATE Latin1_General_100_BIN2 NULL,
    [ACTION] VARCHAR(20) COLLATE Latin1_General_100_BIN2 NULL,
    C_USR_ID VARCHAR(100) NULL,
    C_AT DATETIME2 NULL,
    C_SVC_ID VARCHAR(100) NULL,
    C_PGM_ID VARCHAR(100) NULL,
    U_USR_ID VARCHAR(100) NULL,
    U_AT DATETIME2 NULL,
    U_SVC_ID VARCHAR(100) NULL,
    U_PGM_ID VARCHAR(100) NULL,
    VER BIGINT NULL,
    CONSTRAINT PK_TB_MDM_DATA_RECV_ITEM PRIMARY KEY (RECV_ID, SEQ),
    CONSTRAINT FK_TB_MDM_DATA_RECV_ITEM_RECV FOREIGN KEY (RECV_ID) REFERENCES TB_MDM_DATA_RECV (RECV_ID),
    CONSTRAINT CK_TB_MDM_DATA_RECV_ITEM_ACTION CHECK ([ACTION] IS NULL OR [ACTION] IN ('INSERT','UPDATE','CLOSE','REOPEN','NONE'))
);
