-- 배경:
--   출력물관리 > Tag관리(qpr/tagManagement)를 목업 「TAG 발행 시뮬레이터」 기준의 TAG 발행 규칙 편집기로
--   새로 만든다(계약 docs/mqc/demo/tag-contract.md). 옛 프로그램(Tag 발행·재발행 요청·처리 이력, V3 TB_MQC_TAG)은 지운다.
--   V3 는 이미 적용된 파일이라 고치지 않고, 여기서 옛 표와 출력물 이력(TB_MQC_OUTPUT_HIST)의 TAG 행을 지운다.
--   TB_MQC_OUTPUT_HIST 는 이제 쓰는 곳이 없지만 지우지 않고 둔다.
--
--   새 프로그램은 문서 편집을 화면이 하고 서버는 저장만 한다. 문서는 하나(DOC_ID 'MAIN')이고 본문은 불투명한
--   JSON(CLOB, 수백 KB 가 될 수 있다)이다. BODY_JSON = 지금 편집 중인 본문, BASE_JSON = 승인된 적용본(비교 기준).
--   승인하면 DOC_VER 를 올리고 TB_MQC_TAG_VER 에 1행을 쌓는다. 시연 초기 데이터는 넣지 않는다
--   (화면이 문서가 없으면 기본 문서를 INIT 으로 넣는다). 표 모양은 V6 의 품질보증서 표(TB_MQC_WTY_*)와 같다.
--
-- 칼럼 순서 = PK → 엔티티 필드 선언 순서. 시각은 DATE(초 단위, KST). 감사 칸은 두지 않는다(UPD_BY·UPD_AT 를 서비스가 쓴다).
-- 문서 버전 칼럼 이름은 낙관적 잠금 VER 와 헷갈리지 않게 DOC_VER 로 둔다.
-- ============================================================

-- ── 옛 Tag 지우기 ──────────────────────────────────────
DELETE FROM TB_MQC_OUTPUT_HIST WHERE DOC_TP = 'TAG';
DROP TABLE TB_MQC_TAG PURGE;

-- ── 새 표 ──────────────────────────────────────────────
-- TAG 문서(한 행, DOC_ID = 'MAIN'). STAT_CD: APPLIED 적용본과 같음 · DRAFT 고치는 중 · PENDING 승인 대기.
CREATE TABLE TB_MQC_TAG_DOC (
    DOC_ID       VARCHAR2(20 CHAR)   NOT NULL,
    DOC_VER      NUMBER(9)           NOT NULL,
    STAT_CD      VARCHAR2(10 CHAR)   NOT NULL,
    BODY_JSON    CLOB                NOT NULL,
    BASE_JSON    CLOB                NOT NULL,
    UPD_BY       VARCHAR2(50 CHAR),
    UPD_AT       DATE                NOT NULL,
    CONSTRAINT PK_TB_MQC_TAG_DOC PRIMARY KEY (DOC_ID),
    CONSTRAINT CK_TB_MQC_TAG_DOC_01 CHECK (STAT_CD IN ('APPLIED', 'DRAFT', 'PENDING'))
);

-- 승인 버전 기록(INIT = v1, 승인마다 1행). BODY_JSON = 그 버전의 적용본.
CREATE TABLE TB_MQC_TAG_VER (
    DOC_ID       VARCHAR2(20 CHAR)   NOT NULL,
    DOC_VER      NUMBER(9)           NOT NULL,
    BODY_JSON    CLOB                NOT NULL,
    MEMO_TXT     VARCHAR2(1000 CHAR),
    APRV_BY      VARCHAR2(50 CHAR),
    APRV_AT      DATE                NOT NULL,
    CONSTRAINT PK_TB_MQC_TAG_VER PRIMARY KEY (DOC_ID, DOC_VER)
);

-- 처리 이력. ACT_CD: INIT · DRAFT · REQUEST · UNREQUEST · DISCARD · APPROVE · RESET.
CREATE TABLE TB_MQC_TAG_HIST (
    HIST_NO      NUMBER(19)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
    DOC_ID       VARCHAR2(20 CHAR),
    ACT_CD       VARCHAR2(10 CHAR)   NOT NULL,
    MSG_TXT      VARCHAR2(1000 CHAR),
    ACT_BY       VARCHAR2(50 CHAR),
    ACT_AT       DATE                NOT NULL,
    CONSTRAINT PK_TB_MQC_TAG_HIST PRIMARY KEY (HIST_NO)
);
CREATE INDEX IX_TB_MQC_TAG_HIST_01 ON TB_MQC_TAG_HIST (ACT_AT);
