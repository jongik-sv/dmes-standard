-- 대상 스키마: MQCAPUSER   위치: mqc
-- 이 파일은 그 스키마 주인으로 접속해 실행된다(앱 Flyway 또는 pdb.mjs template-schema, 운영은 DBA).
--
-- 배경:
--   출력물관리 > 검사증명서관리(qpr/inspectionCertificate)를 목업 「검사증명서 발행 시뮬레이터」 기준으로 새로 만든다
--   (계약 docs/mqc/demo/mtc-contract.md). 옛 프로그램(발행 요청 → 검토 → 발행, V3 TB_MQC_INSP_CERT)은 지운다.
--   V3 는 이미 적용된 파일이라 고치지 않고, 여기서 옛 표와 출력물 이력(TB_MQC_OUTPUT_HIST)의 MTC 행을 지운다.
--
--   새 프로그램은 값 계산을 화면(TS 엔진)이 하고 서버는 저장만 한다. 양식·예외 규칙·증명서 원천·단건 수정·이미지는
--   본문을 불투명한 JSON(CLOB, BODY_JSON)으로 두고, 서버가 읽는 몇 개 값만 칼럼으로 뺀다(목록 표시·검사용).
--   발행본(TB_MQC_MTC_ISSUE)은 증명서마다 한 행이고 재발행하면 SNAP_JSON 을 바꾸고 RISSU_CNT 를 올린다.
--   시연 초기 데이터는 SQL 로 넣지 않는다. 서비스가 classpath mqc/mtc/seed.json 을 읽어 첫 조회(표가 비었을 때)와
--   초기화(reset) 때 넣는다.
--
-- 칼럼 순서 = PK → 엔티티 필드 선언 순서. 시각은 DATE(초 단위, KST). 감사 칸은 두지 않는다(UPD_BY·UPD_AT 를 서비스가 쓴다).
-- ============================================================

-- ── 옛 검사증명서 지우기 ─────────────────────────────────
DELETE FROM TB_MQC_OUTPUT_HIST WHERE DOC_TP = 'MTC';
DROP TABLE TB_MQC_INSP_CERT PURGE;

-- ── 새 표 ──────────────────────────────────────────────
-- 양식(en 수출 영문 · ko 내수 한글 · es 스페인어). 본문 = { applied, draft, pending, hist }.
CREATE TABLE TB_MQC_MTC_FORM (
    FORM_KEY     VARCHAR2(10 CHAR)   NOT NULL,
    SORT_SEQ     NUMBER(5)           NOT NULL,
    APLY_VER     NUMBER(5),
    PEND_YN      NUMBER(1,0)         DEFAULT 0 NOT NULL,
    BODY_JSON    CLOB                NOT NULL,
    UPD_BY       VARCHAR2(50 CHAR),
    UPD_AT       DATE                NOT NULL,
    CONSTRAINT PK_TB_MQC_MTC_FORM PRIMARY KEY (FORM_KEY),
    CONSTRAINT CK_TB_MQC_MTC_FORM_01 CHECK (PEND_YN IN (0, 1))
);

-- 예외 규칙(R1 …). 목록 순서(SORT_SEQ)는 우선순위가 같을 때 계산에 쓰이므로 저장 순서를 지킨다.
CREATE TABLE TB_MQC_MTC_RULE (
    RULE_ID      VARCHAR2(20 CHAR)   NOT NULL,
    SORT_SEQ     NUMBER(5)           NOT NULL,
    RULE_CD      VARCHAR2(30 CHAR),
    RULE_NM      VARCHAR2(200 CHAR),
    STAT_CD      VARCHAR2(20 CHAR),
    PRIO         NUMBER(5),
    BODY_JSON    CLOB                NOT NULL,
    UPD_BY       VARCHAR2(50 CHAR),
    UPD_AT       DATE                NOT NULL,
    CONSTRAINT PK_TB_MQC_MTC_RULE PRIMARY KEY (RULE_ID)
);

-- 증명서 원천(인터페이스 데이터, C1 … · 신규 수신 N001 …). MTC_NO = 본문 head.mtc.
CREATE TABLE TB_MQC_MTC_CERT (
    CERT_ID      VARCHAR2(20 CHAR)   NOT NULL,
    SORT_SEQ     NUMBER(5)           NOT NULL,
    MTC_NO       VARCHAR2(30 CHAR),
    CERT_KND     VARCHAR2(10 CHAR),
    CUS_CD       VARCHAR2(30 CHAR),
    BODY_JSON    CLOB                NOT NULL,
    UPD_BY       VARCHAR2(50 CHAR),
    UPD_AT       DATE                NOT NULL,
    CONSTRAINT PK_TB_MQC_MTC_CERT PRIMARY KEY (CERT_ID)
);
CREATE INDEX IX_TB_MQC_MTC_CERT_01 ON TB_MQC_MTC_CERT (MTC_NO);

-- 단건 수정(증명서 한 건만 바꾸는 값). 키 = 증명서 id.
CREATE TABLE TB_MQC_MTC_CERT_OVR (
    CERT_ID      VARCHAR2(20 CHAR)   NOT NULL,
    SORT_SEQ     NUMBER(5)           NOT NULL,
    BODY_JSON    CLOB                NOT NULL,
    UPD_BY       VARCHAR2(50 CHAR),
    UPD_AT       DATE                NOT NULL,
    CONSTRAINT PK_TB_MQC_MTC_CERT_OVR PRIMARY KEY (CERT_ID)
);

-- 서명·도장 이미지 등록함. 본문 = { kind, remark, data(data URL) }.
CREATE TABLE TB_MQC_MTC_IMG (
    IMG_NM       VARCHAR2(200 CHAR)  NOT NULL,
    SORT_SEQ     NUMBER(5)           NOT NULL,
    IMG_KND      VARCHAR2(10 CHAR),
    BODY_JSON    CLOB                NOT NULL,
    UPD_BY       VARCHAR2(50 CHAR),
    UPD_AT       DATE                NOT NULL,
    CONSTRAINT PK_TB_MQC_MTC_IMG PRIMARY KEY (IMG_NM)
);

-- 발행본(증명서마다 한 행). ISSUE_NO 는 첫 발행 순번(기존 최대 + 1), 재발행해도 그대로다.
-- 위변조방지(목업 수준, 계약 §5): DOC_HASH = SNAP_JSON 의 SHA-256(16진 64자), VRFY_CD = 진위 확인 번호(XXXX-XXXX-XXXX,
-- 해시 + 발행 번호 + 재발행 횟수에서 유도). 발행·재발행마다 새로 만든다.
CREATE TABLE TB_MQC_MTC_ISSUE (
    CERT_ID      VARCHAR2(20 CHAR)   NOT NULL,
    ISSUE_NO     NUMBER(9)           NOT NULL,
    MTC_NO       VARCHAR2(30 CHAR),
    RISSU_CNT    NUMBER(5)           DEFAULT 0 NOT NULL,
    RISSU_RSN    VARCHAR2(500 CHAR),
    VRFY_CD      VARCHAR2(14 CHAR)   NOT NULL,
    DOC_HASH     VARCHAR2(64 CHAR)   NOT NULL,
    SNAP_JSON    CLOB                NOT NULL,
    ISSUE_BY     VARCHAR2(50 CHAR),
    ISSUE_AT     DATE                NOT NULL,
    CONSTRAINT PK_TB_MQC_MTC_ISSUE PRIMARY KEY (CERT_ID),
    CONSTRAINT UX_TB_MQC_MTC_ISSUE_01 UNIQUE (ISSUE_NO),
    CONSTRAINT UX_TB_MQC_MTC_ISSUE_02 UNIQUE (VRFY_CD)
);

-- 처리 이력. ACT_CD: 서버가 쓰는 ISSUE·AUTO_ISSUE·REISSUE·RECEIVE·RESET 과 화면이 보내는 저장 동작(FORM_DRAFT·RULE_SAVE 등).
-- DOC_KND: FORM·RULE·CERT·OVR·IMG(초기화는 비어 있다). VERIFY 는 진위 확인 조회다.
-- VRFY_CD: ISSUE·AUTO_ISSUE 는 새로 만든 번호, REISSUE 는 대체된(이전) 번호, VERIFY 는 조회한 번호. 대체된 번호 판정(SUPERSEDED)에 쓴다.
CREATE TABLE TB_MQC_MTC_HIST (
    HIST_NO      NUMBER(19)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
    DOC_KND      VARCHAR2(10 CHAR),
    DOC_NO       VARCHAR2(200 CHAR),
    ACT_CD       VARCHAR2(30 CHAR)   NOT NULL,
    MSG_TXT      VARCHAR2(1000 CHAR),
    RSN_TXT      VARCHAR2(500 CHAR),
    VRFY_CD      VARCHAR2(14 CHAR),
    ACT_BY       VARCHAR2(50 CHAR),
    ACT_AT       DATE                NOT NULL,
    CONSTRAINT PK_TB_MQC_MTC_HIST PRIMARY KEY (HIST_NO)
);
CREATE INDEX IX_TB_MQC_MTC_HIST_01 ON TB_MQC_MTC_HIST (ACT_AT);
CREATE INDEX IX_TB_MQC_MTC_HIST_02 ON TB_MQC_MTC_HIST (VRFY_CD);
