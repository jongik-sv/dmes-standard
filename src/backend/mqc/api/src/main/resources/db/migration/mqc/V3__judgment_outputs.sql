-- ============================================================
-- V3: 품질판정·출력물(품질보증서·검사증명서·Tag) 표와 시연 데이터
-- ============================================================
--
-- 대상 스키마: MQCAPUSER   위치: mqc
-- 이 파일은 그 스키마 주인으로 접속해 실행된다(앱 Flyway 또는 pdb.mjs template-schema, 운영은 DBA).
--
-- 배경:
--   mqc 시연 화면 qjd/qualityJudgment(품질판정)·qpr/qualityCertificate(품질보증서관리)·qpr/inspectionCertificate(검사증명서관리)·
--   qpr/tagManagement(Tag관리)의 업무 기록을 둔다. 코일·검사 항목·화학 성분은 생산·검사 실적의 시연용 사본이고,
--   판정·보증서·증명서·Tag·처리 이력은 화면 처리로 바뀐다. 주문 키(ORD_NO)는 V4 주문 표와 문자열로만 잇는다(FK 없음).
--   시연 데이터는 고정값이다(난수·상대 날짜 없음). 고객은 가명(수요가 A~D)이다.
--
-- 상태 코드(화면 표시는 서비스가 한글 이름으로 바꾼다):
--   판정 JDG_STAT·SUGG_STAT: WAIT 판정대기 · PASS 합격 · FAIL 불합격 · HOLD 보류
--   검사 항목 RSLT_CD: PASS 합 · FAIL 부 · HOLD 보류 · NONE 미검
--   품질보증서 STAT_CD: DRAFT 초안 · ISSUED 발행 · REISSUED 재발행 · RECALLED 회수
--   검사증명서 STAT_CD: REVIEW 검토중 · ISSUED 발행 · HOLD 보류
--   Tag STAT_CD: WAIT 대기 · ISSUED 발행 · REISSUED 재발행 · DISCARDED 폐기,  TAG_KND: PROC 공정 Tag · SHIP 출하 Tag
-- 컬럼 순서: PK → 엔티티 필드 순서 → VER → 감사 칸(CactusAuditEntity 선언 순서).
-- ============================================================

-- 코일(생산 실적 사본). 주문·고객·제품 값은 주문 시점 값을 그대로 둔다.
CREATE TABLE TB_MQC_COIL (
    COIL_NO      VARCHAR2(20 CHAR)   NOT NULL,
    ORD_NO       VARCHAR2(20 CHAR)   NOT NULL,
    CUS_NM       VARCHAR2(50 CHAR),
    PO_NO        VARCHAR2(30 CHAR),
    PRD_CD       VARCHAR2(5 CHAR)    NOT NULL,
    PRD_NM       VARCHAR2(30 CHAR),
    SPEC_CD      VARCHAR2(30 CHAR),
    THK          NUMBER(6,3),
    WTH          NUMBER(6,0),
    WGT          NUMBER(8,0),
    LINE_CD      VARCHAR2(10 CHAR),
    HEAT_NO      VARCHAR2(20 CHAR),
    PROD_AT      DATE,
    INSP_BY      VARCHAR2(50 CHAR),
    INSP_AT      DATE,
    CONSTRAINT PK_TB_MQC_COIL PRIMARY KEY (COIL_NO)
);
CREATE INDEX IX_TB_MQC_COIL_01 ON TB_MQC_COIL (INSP_AT);
CREATE INDEX IX_TB_MQC_COIL_02 ON TB_MQC_COIL (ORD_NO);

-- 코일 검사 항목(도금량·표면·YP·TS·EL·두께 편차). 기준은 품질설계결과에서 내려온 값의 사본이다.
-- CRIT_TP: RANGE(하한·상한, 한쪽만 있으면 그쪽만 본다) · GRADE(등급 A 가 가장 좋고 GRADE_LMT 까지 합격).
CREATE TABLE TB_MQC_COIL_INSP (
    COIL_NO      VARCHAR2(20 CHAR)   NOT NULL,
    ITEM_CD      VARCHAR2(10 CHAR)   NOT NULL,
    SEQ          NUMBER(3)           NOT NULL,
    ITEM_NM      VARCHAR2(30 CHAR)   NOT NULL,
    ITEM_GRP     VARCHAR2(10 CHAR)   NOT NULL,
    UNIT_NM      VARCHAR2(10 CHAR),
    CRIT_TP      VARCHAR2(10 CHAR)   NOT NULL,
    CRIT_TXT     VARCHAR2(30 CHAR),
    LOWER_VAL    NUMBER(12,4),
    UPPER_VAL    NUMBER(12,4),
    GRADE_LMT    VARCHAR2(2 CHAR),
    MEAS_VAL     VARCHAR2(20 CHAR),
    RSLT_CD      VARCHAR2(10 CHAR)   NOT NULL,
    VER          NUMBER(19)          DEFAULT 0,
    C_USR_ID     VARCHAR2(100 CHAR),
    C_AT         TIMESTAMP(6),
    C_SVC_ID     VARCHAR2(100 CHAR),
    C_PGM_ID     VARCHAR2(100 CHAR),
    U_USR_ID     VARCHAR2(100 CHAR),
    U_AT         TIMESTAMP(6),
    U_SVC_ID     VARCHAR2(100 CHAR),
    U_PGM_ID     VARCHAR2(100 CHAR),
    CONSTRAINT PK_TB_MQC_COIL_INSP PRIMARY KEY (COIL_NO, ITEM_CD),
    CONSTRAINT CK_TB_MQC_COIL_INSP_01 CHECK (CRIT_TP IN ('RANGE', 'GRADE')),
    CONSTRAINT CK_TB_MQC_COIL_INSP_02 CHECK (RSLT_CD IN ('PASS', 'FAIL', 'HOLD', 'NONE'))
);

-- 코일 판정. SUGG_STAT 은 검사 항목으로 계산한 시스템 제안, JDG_STAT 은 검사자가 확정한 상태다.
