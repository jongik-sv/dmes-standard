    NOTE         VARCHAR2(500 CHAR),
    VER          NUMBER(19)          DEFAULT 0,
    C_USR_ID     VARCHAR2(100 CHAR),
    C_AT         TIMESTAMP(6),
    C_SVC_ID     VARCHAR2(100 CHAR),
    C_PGM_ID     VARCHAR2(100 CHAR),
    U_USR_ID     VARCHAR2(100 CHAR),
    U_AT         TIMESTAMP(6),
    U_SVC_ID     VARCHAR2(100 CHAR),
    U_PGM_ID     VARCHAR2(100 CHAR),
    CONSTRAINT PK_TB_MQC_COIL_JDG PRIMARY KEY (COIL_NO),
    CONSTRAINT CK_TB_MQC_COIL_JDG_01 CHECK (JDG_STAT IN ('WAIT', 'PASS', 'FAIL', 'HOLD'))
);

