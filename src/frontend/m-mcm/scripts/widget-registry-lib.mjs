/**
 * 위젯 등록부 생성 규칙(스펙 2026-10-02-widget-foundation §2.3) — generate-widget-registry.mjs 가 쓰고 node:test 로 시험한다.
 * 위젯 폴더: widgets/{group}/{name}/widget.meta.ts + widget.tsx. 이름이 _ 로 시작하는 폴더는 건너뛴다(공용 도우미 자리).
 * meta 는 TS 라 값을 실행하지 않고, id 문자열이 폴더와 같은지만 정규식으로 확인한다. 크기 범위는 shared validateWidgetMeta 가 실행 시 검사한다.
 */
import { promises as fs } from "node:fs";
import * as path from "node:path";

async function exists(p) {
  try {
    await fs.access(p);
    return true;
  } catch {
    return false;
  }
}

export function keyToId(key) {
  return key.replace("/", ".");
}

/** rootDir 아래 위젯을 모은다 → [{ key: "group/name", id: "group.name" }] (key 이름순). */
export async function collectWidgets(rootDir) {
  if (!(await exists(rootDir))) return [];
  const out = [];
  for (const g of await fs.readdir(rootDir, { withFileTypes: true })) {
    if (!g.isDirectory() || g.name.startsWith("_")) continue;
    for (const n of await fs.readdir(path.join(rootDir, g.name), { withFileTypes: true })) {
      if (!n.isDirectory() || n.name.startsWith("_")) continue;
      const dir = path.join(rootDir, g.name, n.name);
      const metaPath = path.join(dir, "widget.meta.ts");
      if (!(await exists(metaPath))) continue;
      const key = `${g.name}/${n.name}`;
      const id = keyToId(key);
      if (!(await exists(path.join(dir, "widget.tsx")))) {
        throw new Error(`[widget-registry] ${key}: widget.meta.ts 짝인 widget.tsx 가 없습니다.`);
      }
      const src = await fs.readFile(metaPath, "utf8");
      const m = src.match(/\bid\s*:\s*["']([^"']+)["']/);
      if (!m || m[1] !== id) {
        throw new Error(`[widget-registry] ${key}: widget.meta.ts 의 id 는 "${id}" 여야 합니다(지금: ${m ? `"${m[1]}"` : "없음"}).`);
      }
      out.push({ key, id });
    }
  }
  out.sort((a, b) => a.key.localeCompare(b.key));
  return out;
}

const TYPE_ID_RE = /^[a-z0-9]+(-[a-z0-9]+)*$/;
const TYPE_FILES = ["type.meta.ts", "renderer.tsx", "editor.tsx"];

/**
 * 위젯 유형 폴더를 모은다(스펙 2026-10-02-widget-admin-generic §3) → [{ id }] (이름순).
 * 유형 폴더: widget-types/{typeId}/type.meta.ts + renderer.tsx + editor.tsx. 이름이 _ 로 시작하는 폴더는 공용 도우미 자리라 건너뛴다.
 */
export async function collectWidgetTypes(rootDir) {
  if (!(await exists(rootDir))) return [];
  const out = [];
  for (const d of await fs.readdir(rootDir, { withFileTypes: true })) {
    if (!d.isDirectory() || d.name.startsWith("_")) continue;
    const dir = path.join(rootDir, d.name);
    if (!TYPE_ID_RE.test(d.name)) {
      throw new Error(`[widget-type-registry] ${d.name}: 유형 폴더 이름은 소문자·숫자·하이픈이어야 합니다.`);
    }
    for (const f of TYPE_FILES) {
      if (!(await exists(path.join(dir, f)))) {
        throw new Error(`[widget-type-registry] ${d.name}: ${f} 가 없습니다(필요: ${TYPE_FILES.join(", ")}).`);
      }
    }
    const src = await fs.readFile(path.join(dir, "type.meta.ts"), "utf8");
    const m = src.match(/\bid\s*:\s*["']([^"']+)["']/);
    if (!m || m[1] !== d.name) {
      throw new Error(`[widget-type-registry] ${d.name}: type.meta.ts 의 id 는 "${d.name}" 여야 합니다(지금: ${m ? `"${m[1]}"` : "없음"}).`);
    }
    out.push({ id: d.name });
  }
  out.sort((a, b) => a.id.localeCompare(b.id));
  return out;
}

/** types: [{ id }] → widget-type-registry.ts 내용. import 경로는 정적 리터럴(turbopack). */
export function renderTypeRegistry(types) {
  const seen = new Set();
  for (const t of types) {
    if (seen.has(t.id)) throw new Error(`[widget-type-registry] 유형 id 중복: ${t.id}`);
    seen.add(t.id);
  }
  const imports = types.map((t, i) => `import { meta as t${i} } from ${JSON.stringify(`@/widget-types/${t.id}/type.meta`)};`).join("\n");
  const rows = types
    .map(
      (t, i) =>
        `  ${JSON.stringify(t.id)}: {\n    meta: t${i},\n    loadRenderer: () => import(${JSON.stringify(`@/widget-types/${t.id}/renderer`)}),\n    loadEditor: () => import(${JSON.stringify(`@/widget-types/${t.id}/editor`)}),\n  },`
    )
    .join("\n");
  return `// AUTO-GENERATED by scripts/generate-widget-registry.mjs — do not edit manually.
// 갱신 방법: \`node scripts/generate-widget-registry.mjs\` (predev/prebuild 훅 자동 실행).
// widget-types/{typeId}/type.meta.ts(정적) + renderer.tsx·editor.tsx(지연 로딩). 스펙 2026-10-02-widget-admin-generic §3.
import type { WidgetTypeRegistry } from "@dk-oasis/shared/widget";
${imports ? `\n${imports}\n` : ""}
export const WIDGET_TYPE_REGISTRY: WidgetTypeRegistry = {
${rows}
};
`;
}

/** entries: [{ id, metaImport, bodyImport }] → widget-registry.ts 내용. import 경로는 정적 리터럴(turbopack). */
export function renderRegistry(entries) {
  const seen = new Set();
  for (const e of entries) {
    if (seen.has(e.id)) throw new Error(`[widget-registry] 위젯 id 중복: ${e.id}`);
    seen.add(e.id);
  }
  const imports = entries.map((e, i) => `import { meta as m${i} } from ${JSON.stringify(e.metaImport)};`).join("\n");
  const rows = entries
    .map((e, i) => `  ${JSON.stringify(e.id)}: { meta: m${i}, load: () => import(${JSON.stringify(e.bodyImport)}) },`)
    .join("\n");
  return `// AUTO-GENERATED by scripts/generate-widget-registry.mjs — do not edit manually.
// 갱신 방법: \`node scripts/generate-widget-registry.mjs\` (predev/prebuild 훅 자동 실행).
// widgets/{group}/{name}/widget.meta.ts(정적) + widget.tsx(지연 로딩). 스펙 2026-10-02-widget-foundation §2.3.
import type { WidgetRegistry } from "@dk-oasis/shared/widget";
${imports ? `\n${imports}\n` : ""}
export const WIDGET_REGISTRY: WidgetRegistry = {
${rows}
};
`;
}
