CREATE TABLE TB_MDM_CODE_VER (
    MARU_CODE_ID VARCHAR(50) NOT NULL,
    VER NUMERIC(7,3) NOT NULL,
    VER_KIND VARCHAR(20) NOT NULL,
    RESTORED_FROM NUMERIC(7,3),
    STATUS VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    OWNER_ID VARCHAR(50),
    APPLY_FROM TEXT,
    APPLY_TO TEXT,
    DESCRIPTION TEXT,
    REQUESTED_BY VARCHAR(50),
    REQUESTED_AT TEXT,
    EMERGENCY_YN VARCHAR(1) NOT NULL DEFAULT 'N',
    EMERGENCY_REASON TEXT,
    APPROVED_BY VARCHAR(50),
    APPROVED_AT TEXT,
    REJECT_REASON TEXT,
    RELEASED_AT TEXT,
    CANCELLED_AT TEXT,
    CANCEL_REASON TEXT,
    ROW_VERSION INTEGER NOT NULL DEFAULT 0,
    C_USR_ID VARCHAR(100),
    C_AT TIMESTAMP,
    C_SVC_ID VARCHAR(100),
    C_PGM_ID VARCHAR(100),
    U_USR_ID VARCHAR(100),
    U_AT TIMESTAMP,
    U_SVC_ID VARCHAR(100),
    U_PGM_ID VARCHAR(100),
    AUD_VER INTEGER,
    CONSTRAINT PK_TB_MDM_CODE_VER PRIMARY KEY (MARU_CODE_ID, VER),
    CONSTRAINT FK_TB_MDM_CODE_VER_CODE FOREIGN KEY (MARU_CODE_ID) REFERENCES TB_MDM_CODE (MARU_CODE_ID),
    CONSTRAINT CK_TB_MDM_CODE_VER_KIND CHECK (VER_KIND IN ('MAJOR','MINOR')),
    CONSTRAINT CK_TB_MDM_CODE_VER_STATUS CHECK (STATUS IN ('DRAFT','REQUESTED','APPROVED','RELEASED','CANCELLED')),
    CONSTRAINT CK_TB_MDM_CODE_VER_APPLY CHECK (STATUS = 'DRAFT' OR (APPLY_FROM IS NOT NULL AND APPLY_TO IS NOT NULL)),
    CONSTRAINT CK_TB_MDM_CODE_VER_EMERGENCY_YN CHECK (EMERGENCY_YN IN ('Y','N'))
);

CREATE TABLE TB_MDM_CODE_ITEM (
    MARU_CODE_ID VARCHAR(50) NOT NULL,
    CODE VARCHAR(50) NOT NULL,
