-- TSK-02-03 영역 04 (dmc) SQLite DDL — TB_MDM_CODE · CODE_SYSTEM · CODE_VER · CODE_ITEM · CODE_CATE · CODE_CATE_ITEM · CODE_RECV
-- 근거: docs/mdm/tasks/TSK-02-03/design.md §6.3. 전체 배포 방식(F11) — 행 단위 chg_seq 없음.
-- 이탈: TB_MDM_CODE_VER·TB_MDM_CODE_RECV 는 원천 업무 칼럼 VER(버전 번호)과 감사 카운터 VER 이 이름이 겹쳐
-- (design.md §6.0 감사 9칼럼 VS §6.3 업무 칼럼, 두 곳 모두 "VER"), 이 두 테이블에 한해 감사 카운터만 AUD_VER 로 개명한다.
-- 근거: CactusAuditEntity(src/backend/cactus-core)는 @Column(name="VER") 로 고정이지만 @MappedSuperclass 라
-- 하위 엔티티가 표준 JPA @AttributeOverride(name="version", column=@Column(name="AUD_VER")) 로 재매핑할 수 있다(코드 변경 없음).
-- decisions.md D-020 계열 참조.

CREATE TABLE TB_MDM_CODE (
    MARU_CODE_ID VARCHAR(50) NOT NULL,
    MARU_CODE_NAME TEXT NOT NULL,
    STATUS VARCHAR(20) NOT NULL DEFAULT 'CREATED',
    SOURCE_KIND VARCHAR(20) NOT NULL,
    SOURCE_SYSTEM VARCHAR(20),
    DESCRIPTION TEXT,
    ATTR01_NAME TEXT, ATTR02_NAME TEXT, ATTR03_NAME TEXT, ATTR04_NAME TEXT, ATTR05_NAME TEXT,
    ATTR06_NAME TEXT, ATTR07_NAME TEXT, ATTR08_NAME TEXT, ATTR09_NAME TEXT, ATTR10_NAME TEXT,
    LVL_CNT INTEGER NOT NULL DEFAULT 0,
    LAST_CHG_SEQ INTEGER NOT NULL DEFAULT 0,
    C_USR_ID VARCHAR(100),
    C_AT TIMESTAMP,
    C_SVC_ID VARCHAR(100),
    C_PGM_ID VARCHAR(100),
    U_USR_ID VARCHAR(100),
    U_AT TIMESTAMP,
    U_SVC_ID VARCHAR(100),
    U_PGM_ID VARCHAR(100),
    VER INTEGER,
    CONSTRAINT PK_TB_MDM_CODE PRIMARY KEY (MARU_CODE_ID),
    CONSTRAINT FK_TB_MDM_CODE_SYSTEM_SRC FOREIGN KEY (SOURCE_SYSTEM) REFERENCES TB_MDM_SYSTEM (SYSTEM_CODE),
    CONSTRAINT CK_TB_MDM_CODE_STATUS CHECK (STATUS IN ('CREATED','INUSE','DEPRECATED')),
    CONSTRAINT CK_TB_MDM_CODE_SRC_KIND CHECK (SOURCE_KIND IN ('MDM','EXTERNAL')),
    CONSTRAINT CK_TB_MDM_CODE_SRC_SYS CHECK ((SOURCE_KIND = 'EXTERNAL' AND SOURCE_SYSTEM IS NOT NULL) OR (SOURCE_KIND = 'MDM' AND SOURCE_SYSTEM IS NULL)),
    CONSTRAINT CK_TB_MDM_CODE_LVL_CNT CHECK (LVL_CNT BETWEEN 0 AND 5)
);

