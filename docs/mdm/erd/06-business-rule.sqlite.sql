-- RULE_VAR.DOMAIN_ID→TB_MDM_DOMAIN(02) 은 정방향 참조라 인라인 FK 가능(F13).

CREATE TABLE TB_MDM_RULE (
    MARU_RULE_ID VARCHAR(50) NOT NULL,
    MARU_RULE_NAME TEXT NOT NULL,
    RULE_KIND VARCHAR(20) NOT NULL,
    STATUS VARCHAR(20) NOT NULL DEFAULT 'CREATED',
    SOURCE_KIND VARCHAR(20) NOT NULL,
    SOURCE_SYSTEM VARCHAR(20),
    DESCRIPTION TEXT,
    USAGE_NOTE TEXT,
    LAST_VAR_ID INTEGER NOT NULL DEFAULT 0,
    LAST_ROW_ID INTEGER NOT NULL DEFAULT 0,
    LAST_CASE_ID INTEGER NOT NULL DEFAULT 0,
    C_USR_ID VARCHAR(100),
    C_AT TIMESTAMP,
    C_SVC_ID VARCHAR(100),
    C_PGM_ID VARCHAR(100),
    U_USR_ID VARCHAR(100),
    U_AT TIMESTAMP,
    U_SVC_ID VARCHAR(100),
    U_PGM_ID VARCHAR(100),
    VER INTEGER,
    CONSTRAINT PK_TB_MDM_RULE PRIMARY KEY (MARU_RULE_ID),
    CONSTRAINT FK_TB_MDM_RULE_SYSTEM_SRC FOREIGN KEY (SOURCE_SYSTEM) REFERENCES TB_MDM_SYSTEM (SYSTEM_CODE),
    CONSTRAINT CK_TB_MDM_RULE_KIND CHECK (RULE_KIND IN ('DECISION','DERIVE')),
    CONSTRAINT CK_TB_MDM_RULE_STATUS CHECK (STATUS IN ('CREATED','INUSE','DEPRECATED')),
    CONSTRAINT CK_TB_MDM_RULE_SRC_KIND CHECK (SOURCE_KIND IN ('MDM','EXTERNAL')),
    CONSTRAINT CK_TB_MDM_RULE_SRC_SYS CHECK ((SOURCE_KIND = 'EXTERNAL' AND SOURCE_SYSTEM IS NOT NULL) OR (SOURCE_KIND = 'MDM' AND SOURCE_SYSTEM IS NULL))
);

