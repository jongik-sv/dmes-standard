-- 근거: docs/mdm/tasks/TSK-02-03/design.md §6.3. 실행·실측하지 않는다(F4).
-- 이탈: TB_MDM_CODE_VER·TB_MDM_CODE_RECV 의 감사 카운터는 업무 칼럼 VER 과 충돌해 AUD_VER 로 개명(02 SQLite 파일 머리말 참조).
-- TB_MDM_DOMAIN.MARU_CODE_ID → TB_MDM_CODE FK 는 99-cross-area-fk.mssql.sql 에서 후행 추가(§6.6).

CREATE TABLE TB_MDM_CODE (
    MARU_CODE_ID VARCHAR(50) COLLATE Latin1_General_100_BIN2 NOT NULL,
    MARU_CODE_NAME NVARCHAR(100) NOT NULL,
    STATUS VARCHAR(20) COLLATE Latin1_General_100_BIN2 NOT NULL CONSTRAINT DF_TB_MDM_CODE_STATUS DEFAULT ('CREATED'),
    SOURCE_KIND VARCHAR(20) COLLATE Latin1_General_100_BIN2 NOT NULL,
    SOURCE_SYSTEM VARCHAR(20) COLLATE Latin1_General_100_BIN2 NULL,
    DESCRIPTION NVARCHAR(MAX) NULL,
    ATTR01_NAME NVARCHAR(100) NULL, ATTR02_NAME NVARCHAR(100) NULL, ATTR03_NAME NVARCHAR(100) NULL,
    ATTR04_NAME NVARCHAR(100) NULL, ATTR05_NAME NVARCHAR(100) NULL, ATTR06_NAME NVARCHAR(100) NULL,
    ATTR07_NAME NVARCHAR(100) NULL, ATTR08_NAME NVARCHAR(100) NULL, ATTR09_NAME NVARCHAR(100) NULL,
    ATTR10_NAME NVARCHAR(100) NULL,
    LVL_CNT INT NOT NULL CONSTRAINT DF_TB_MDM_CODE_LVL_CNT DEFAULT (0),
    LAST_CHG_SEQ BIGINT NOT NULL CONSTRAINT DF_TB_MDM_CODE_LAST_CHG_SEQ DEFAULT (0),
    C_USR_ID VARCHAR(100) NULL,
    C_AT DATETIME2 NULL,
    C_SVC_ID VARCHAR(100) NULL,
    C_PGM_ID VARCHAR(100) NULL,
    U_USR_ID VARCHAR(100) NULL,
    U_AT DATETIME2 NULL,
    U_SVC_ID VARCHAR(100) NULL,
    U_PGM_ID VARCHAR(100) NULL,
    VER BIGINT NULL,
    CONSTRAINT PK_TB_MDM_CODE PRIMARY KEY (MARU_CODE_ID),
    CONSTRAINT FK_TB_MDM_CODE_SYSTEM_SRC FOREIGN KEY (SOURCE_SYSTEM) REFERENCES TB_MDM_SYSTEM (SYSTEM_CODE),
    CONSTRAINT CK_TB_MDM_CODE_STATUS CHECK (STATUS IN ('CREATED','INUSE','DEPRECATED')),
    CONSTRAINT CK_TB_MDM_CODE_SRC_KIND CHECK (SOURCE_KIND IN ('MDM','EXTERNAL')),
    CONSTRAINT CK_TB_MDM_CODE_SRC_SYS CHECK ((SOURCE_KIND = 'EXTERNAL' AND SOURCE_SYSTEM IS NOT NULL) OR (SOURCE_KIND = 'MDM' AND SOURCE_SYSTEM IS NULL)),
    CONSTRAINT CK_TB_MDM_CODE_LVL_CNT CHECK (LVL_CNT BETWEEN 0 AND 5)
);

CREATE TABLE TB_MDM_CODE_SYSTEM (
    MARU_CODE_ID VARCHAR(50) COLLATE Latin1_General_100_BIN2 NOT NULL,
    SYSTEM_CODE VARCHAR(20) COLLATE Latin1_General_100_BIN2 NOT NULL,
    DESCRIPTION NVARCHAR(MAX) NULL,
    C_USR_ID VARCHAR(100) NULL,
    C_AT DATETIME2 NULL,
    C_SVC_ID VARCHAR(100) NULL,
    C_PGM_ID VARCHAR(100) NULL,
    U_USR_ID VARCHAR(100) NULL,
    U_AT DATETIME2 NULL,
    U_SVC_ID VARCHAR(100) NULL,
    U_PGM_ID VARCHAR(100) NULL,
    VER BIGINT NULL,
    CONSTRAINT PK_TB_MDM_CODE_SYSTEM PRIMARY KEY (MARU_CODE_ID, SYSTEM_CODE),
