CREATE TABLE TB_MDM_CODE_VER (
    MARU_CODE_ID VARCHAR(50) COLLATE Latin1_General_100_BIN2 NOT NULL,
    VER DECIMAL(7,3) NOT NULL,
    VER_KIND VARCHAR(20) COLLATE Latin1_General_100_BIN2 NOT NULL,
    RESTORED_FROM DECIMAL(7,3) NULL,
    STATUS VARCHAR(20) COLLATE Latin1_General_100_BIN2 NOT NULL CONSTRAINT DF_TB_MDM_CODE_VER_STATUS DEFAULT ('DRAFT'),
    OWNER_ID VARCHAR(50) COLLATE Latin1_General_100_BIN2 NULL,
    APPLY_FROM DATETIME2(0) NULL,
    APPLY_TO DATETIME2(0) NULL,
    DESCRIPTION NVARCHAR(MAX) NULL,
    REQUESTED_BY VARCHAR(50) COLLATE Latin1_General_100_BIN2 NULL,
    REQUESTED_AT DATETIME2(0) NULL,
    EMERGENCY_YN VARCHAR(1) COLLATE Latin1_General_100_BIN2 NOT NULL CONSTRAINT DF_TB_MDM_CODE_VER_EMERGENCY_YN DEFAULT ('N'),
    EMERGENCY_REASON NVARCHAR(MAX) NULL,
    APPROVED_BY VARCHAR(50) COLLATE Latin1_General_100_BIN2 NULL,
    APPROVED_AT DATETIME2(0) NULL,
    REJECT_REASON NVARCHAR(MAX) NULL,
    RELEASED_AT DATETIME2(0) NULL,
    CANCELLED_AT DATETIME2(0) NULL,
    CANCEL_REASON NVARCHAR(MAX) NULL,
    ROW_VERSION INT NOT NULL CONSTRAINT DF_TB_MDM_CODE_VER_ROW_VERSION DEFAULT (0),
    C_USR_ID VARCHAR(100) NULL,
    C_AT DATETIME2 NULL,
    C_SVC_ID VARCHAR(100) NULL,
    C_PGM_ID VARCHAR(100) NULL,
    U_USR_ID VARCHAR(100) NULL,
    U_AT DATETIME2 NULL,
    U_SVC_ID VARCHAR(100) NULL,
    U_PGM_ID VARCHAR(100) NULL,
    AUD_VER BIGINT NULL,
    CONSTRAINT PK_TB_MDM_CODE_VER PRIMARY KEY (MARU_CODE_ID, VER),
    CONSTRAINT FK_TB_MDM_CODE_VER_CODE FOREIGN KEY (MARU_CODE_ID) REFERENCES TB_MDM_CODE (MARU_CODE_ID),
    CONSTRAINT CK_TB_MDM_CODE_VER_KIND CHECK (VER_KIND IN ('MAJOR','MINOR')),
    CONSTRAINT CK_TB_MDM_CODE_VER_STATUS CHECK (STATUS IN ('DRAFT','REQUESTED','APPROVED','RELEASED','CANCELLED')),
    CONSTRAINT CK_TB_MDM_CODE_VER_APPLY CHECK (STATUS = 'DRAFT' OR (APPLY_FROM IS NOT NULL AND APPLY_TO IS NOT NULL)),
    CONSTRAINT CK_TB_MDM_CODE_VER_EMERGENCY_YN CHECK (EMERGENCY_YN IN ('Y','N'))
);

